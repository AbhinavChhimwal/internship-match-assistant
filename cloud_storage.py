"""Server-only cloud configuration and a small PostgreSQL connection adapter."""
import os
import re
import tomllib
from pathlib import Path


class StorageUnavailable(RuntimeError):
    """Safe to display: never contains a connection string or provider response."""


def secret(name, default=''):
    value = os.environ.get(name)
    if value is None:
        try:
            values = tomllib.loads((Path(__file__).parent/'.streamlit'/'secrets.toml').read_text(encoding='utf-8-sig'))
            value = values.get(name, default)
        except FileNotFoundError:
            value = default
        except (OSError, tomllib.TOMLDecodeError):
            raise StorageUnavailable('Secrets configuration could not be read. Check its TOML syntax.') from None
    return value if isinstance(value, str) else default


def enabled(path=None):
    return path is None and bool(secret('DATABASE_URL'))


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, parameters=()):
        # Only trusted application SQL passes here; values remain bound parameters.
        ignore = 'INSERT OR IGNORE INTO' in sql
        sql = sql.replace('INSERT OR IGNORE INTO', 'INSERT INTO').replace('?', '%s')
        if ignore:
            sql += ' ON CONFLICT DO NOTHING'
        return self.connection.execute(sql, parameters)

    def executescript(self, sql):
        sql = re.sub(r'\bid INTEGER PRIMARY KEY\b',
                     'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql)
        for statement in sql.split(';'):
            if statement.strip():
                self.execute(statement)


def open_postgres():
    try:
        import psycopg
        from psycopg.rows import dict_row
        return psycopg.connect(secret('DATABASE_URL'), sslmode='require', connect_timeout=10,
            options='-c search_path=internship_match,public -c statement_timeout=20000',
            row_factory=dict_row)
    except Exception:
        raise StorageUnavailable('Database connection unavailable. Check cloud database status and private connection settings.') from None
