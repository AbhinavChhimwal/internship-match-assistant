def test_postgres_adapter_keeps_values_bound_and_converts_schema():
    calls=[]
    class Connection:
        def execute(self,sql,parameters):
            calls.append((sql,parameters))
    con=cloud_storage.PostgresConnection(Connection())
    value="private'; DROP TABLE users; --"
    con.execute('INSERT OR IGNORE INTO users(display_name) VALUES (?)',(value,))
    assert calls[-1]==('INSERT INTO users(display_name) VALUES (%s) ON CONFLICT DO NOTHING',(value,))
    con.executescript('CREATE TABLE users(id INTEGER PRIMARY KEY, display_name TEXT);')
    assert 'GENERATED BY DEFAULT AS IDENTITY' in calls[-1][0]


