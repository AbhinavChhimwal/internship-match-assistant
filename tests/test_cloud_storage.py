def test_cloud_restart_preserves_admin_listing_and_csv_export(tmp_path, monkeypatch):
    """Exercise the durable-catalog branch using a local transactional test store.

    This verifies application behavior, not PostgreSQL/Supabase connectivity.
    """
    from contextlib import contextmanager
    import cloud_startup
    import embeddings
    import catalog_admin
    from import_jobs import read_jobs
    from schemas import Job
    path=tmp_path/'catalog.db'
    code=catalog_admin.create_admin(path=path)
    admin=db.authenticate(code,path)['id']
    original_connect=db.connect
    class Connection:
        def __init__(self, con):
            self.con=con
        def execute(self, sql, parameters=()):
            if 'pg_advisory_xact_lock' in sql:
                return None
            return self.con.execute(sql, parameters)
    @contextmanager
    def connection(path=None):
        with original_connect(tmp_path/'catalog.db') as con:
            yield Connection(con)
    monkeypatch.setattr(db,'connect',connection)
    monkeypatch.setattr(cloud_storage,'enabled',lambda path=None: path is None)
    monkeypatch.setattr(embeddings,'load_embeddings',lambda jobs: {})
    cloud_startup.prepare_catalog()
    count=len(db.get_jobs())
    original=read_jobs('data/jobs.csv')[0].model_dump()
    original.update(source_url='https://example.org/persistent-test',title='Persistent test role')
    job=Job.model_validate(original)
    catalog_admin.add_job(admin,job,indexer=lambda *args: None)
    cloud_startup.prepare_catalog()
    assert len(db.get_jobs())==count+1
    assert b'Persistent test role' in catalog_admin.export_catalog(admin)
    with pytest.raises(PermissionError):
        catalog_admin.add_job(db.authenticate('DUMMY')['id'],job)


