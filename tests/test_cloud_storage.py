@pytest.fixture
def wake(monkeypatch):
    monkeypatch.setattr(supabase_wake, '_checked_at', 0)
    monkeypatch.setattr(supabase_wake, '_restore_requested_at', 0)
    monkeypatch.setattr(supabase_wake, 'secret', lambda key: {
        'SUPABASE_PROJECT_REF': 'a'*20, 'SUPABASE_MANAGEMENT_TOKEN': 'secret-test-only'}[key])
    timer = [1000.0]
    def sleep(seconds):
        timer[0] += seconds
    return lambda: timer[0], sleep


def test_restore_only_once_and_cache_success(wake):
    clock, sleep = wake
    statuses = iter(['INACTIVE', 'INACTIVE', 'COMING_UP', 'ACTIVE_HEALTHY'])
    calls, messages = [], []
    def request(ref, token, method='GET'):
        calls.append(method)
        return {} if method=='POST' else {'status': next(statuses)}
    supabase_wake.ensure_awake(messages.append, request, sleep, clock)
    supabase_wake.ensure_awake(messages.append, request, sleep, clock)
    assert calls == ['GET','POST','GET','GET','GET']
    assert messages


def test_restore_timeout_is_bounded_and_does_not_loop_post(wake):
    clock, sleep = wake
    calls = []
    def request(ref, token, method='GET'):
        calls.append(method)
        return {'status': 'INACTIVE'}
    with pytest.raises(cloud_storage.StorageUnavailable, match='still starting'):
        supabase_wake.ensure_awake(request=request, sleep=sleep, clock=clock, timeout=6)
    assert calls.count('POST')==1


def test_management_errors_never_include_token_or_response():
    def broken(*args, **kwargs):
        raise ValueError('secret-test-only database-password private-provider-body')
    with pytest.raises(cloud_storage.StorageUnavailable) as error:
        supabase_wake.management_request('a'*20, 'secret-test-only', opener=broken)
    assert 'secret-test-only' not in str(error.value)
    assert 'database-password' not in str(error.value)
    assert 'private-provider-body' not in str(error.value)


def test_management_requests_use_fixed_host_and_auth_header():
    import io
    calls=[]
    def opener(request, timeout):
        calls.append(request)
        return io.BytesIO(b'{}')
    supabase_wake.management_request('a'*20,'test-token','POST',opener)
    assert calls[0].full_url=='https://api.supabase.com/v1/projects/'+'a'*20+'/restore'
    assert calls[0].get_method()=='POST'
    assert calls[0].get_header('Authorization')=='Bearer test-token'


